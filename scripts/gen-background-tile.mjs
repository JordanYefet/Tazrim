#!/usr/bin/env node
/**
 * Writes lib/background/lines-tile.data.ts: the "קווים עדינים" background tile
 * (ENG-72), laid out by generateLinesTile in lib/background/lines.ts.
 *
 *   node scripts/gen-background-tile.mjs            -> rewrite the data file
 *   node scripts/gen-background-tile.mjs out.svg    -> also write a 2x2 preview SVG
 *
 * The tile is committed rather than generated at runtime so the server and
 * every browser draw exactly the same paths (see lines.ts).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateLinesTile, TILE_WIDTH, TILE_HEIGHT, LINE_WIDTH } from '../lib/background/lines.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { paths } = generateLinesTile()

const body = paths
  .map(p => `  { d: '${p.d}', color: ${p.color}, copies: ${JSON.stringify(p.copies)} },`)
  .join('\n')
const file = `// Generated by scripts/gen-background-tile.mjs from lib/background/lines.ts. Do not edit.
import type { TilePath } from './lines'

export const LINES_TILE: ReadonlyArray<TilePath> = [
${body}
]
`
fs.writeFileSync(path.join(root, 'lib/background/lines-tile.data.ts'), file)
console.log(`${paths.length} paths, ${paths.reduce((n, p) => n + p.copies.length, 0)} drawn`)

const preview = process.argv[2]
if (preview) {
  const tile = paths
    .flatMap(p => p.copies.map(([dx, dy]) => `<path d="${p.d}" transform="translate(${dx} ${dy})" stroke="${p.color ? '#d946ef' : '#4f46e5'}"/>`))
    .join('')
  const uses = [0, 1].flatMap(i => [0, 1].map(j => `<use href="#t" x="${i * TILE_WIDTH}" y="${j * TILE_HEIGHT}"/>`)).join('')
  fs.writeFileSync(
    preview,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${TILE_WIDTH * 2}" height="${TILE_HEIGHT * 2}" style="background:#fff">
<defs><clipPath id="c"><rect width="${TILE_WIDTH}" height="${TILE_HEIGHT}"/></clipPath>
<g id="t" clip-path="url(#c)" fill="none" stroke-width="${LINE_WIDTH}" stroke-linecap="round" stroke-linejoin="round" opacity="0.35">${tile}</g></defs>
${uses}<path d="M${TILE_WIDTH} 0V${TILE_HEIGHT * 2}M0 ${TILE_HEIGHT}H${TILE_WIDTH * 2}" stroke="#f00" stroke-width="1" opacity="0.3"/></svg>`
  )
}
