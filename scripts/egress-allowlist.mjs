/**
 * Renders what Squid needs (ENG-131, ENG-142) from docker/squid/allowlist.json, the single source of truth.
 *
 *   node scripts/egress-allowlist.mjs          writes docker/squid/banks.txt (every provider's domains, the
 *                                              defaults the Squid wrapper starts from), fills the generated
 *                                              blocks of docker/squid/squid.conf (one port, access list and
 *                                              rule per provider), and refreshes the copies of squid.conf,
 *                                              banks.txt and init.sh inside docker-compose.egress.yml
 *   node scripts/egress-allowlist.mjs --check  exits 1 when any of them is stale
 *
 * Squid's dstdomain wants one entry per line, and warns about (and ignores) an entry that a
 * broader one of the same provider already covers, so those are left out (updater/egress-rules.mjs).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { covers, providerLines } from '../updater/egress-rules.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
export const ALLOWLIST_JSON = path.join(here, '../docker/squid/allowlist.json')
export const BANKS_TXT = path.join(here, '../docker/squid/banks.txt')
export const SQUID_CONF = path.join(here, '../docker/squid/squid.conf')
export const INIT_SH = path.join(here, '../docker/squid/init.sh')
export const LAB_COMPOSE = path.join(here, '../docker/squid/lab.compose.yml')
export const EGRESS_COMPOSE = path.join(here, '../docker-compose.egress.yml')

export function loadAllowlist(file = ALLOWLIST_JSON) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

export { covers }

/** Every domain in the file (own and third-party), in file order, with its provider and why */
export function entries(list) {
  const out = []
  for (const [id, p] of Object.entries(list.providers)) {
    for (const d of p.domains) out.push({ id, domain: d, kind: 'own', why: '' })
    for (const t of p.thirdParty ?? []) out.push({ id, domain: t.domain, kind: 'third-party', why: t.why ?? '' })
  }
  return out
}

/** Squid's port for the app's own calls (everything that is not a provider's browser) */
export const MAIN_PORT = 3128

/** [{ id, port }] in file order */
export function ports(list) {
  return Object.entries(list.providers).map(([id, p]) => ({ id, port: p.port }))
}

/** banks.txt: one section per provider, each with ALL its own domains (the wrapper copies a section to providers/<id>.txt) */
export function render(list) {
  const lines = [
    '# GENERATED by scripts/egress-allowlist.mjs from docker/squid/allowlist.json: do not edit here.',
    '# Every provider\'s domains, one dstdomain per line. Squid does NOT read this file: the Squid wrapper',
    '# (docker/squid/init.sh) copies a provider\'s section to /etc/squid/extra/providers/<id>.txt when that file',
    '# does not exist yet, and from then on the updater keeps those files (only the providers the household uses).',
    '# A leading dot matches the domain and every subdomain; no dot = that exact host only.',
    '# "third-party" = a host the provider\'s pages load that login needs (found by scripts/egress-survey.mjs).',
    '',
  ]
  for (const [id, p] of Object.entries(list.providers)) {
    lines.push(`# --- ${id}: ${p.name}`, ...providerLines(p), '')
  }
  return lines.join('\n')
}

/** The generated parts of squid.conf, by block name */
export function confBlocks(list) {
  const all = ports(list)
  const portLines = [`http_port ${MAIN_PORT} name=p_main`, ...all.map(({ id, port }) => `http_port ${port} name=p_${id}`)]
  const acls = ['acl via_main myportname p_main']
  for (const { id } of all) {
    acls.push(
      `acl via_${id} myportname p_${id}`,
      `acl dst_${id} dstdomain "/etc/squid/extra/providers/${id}.txt"`,
      `acl extra_${id} dstdomain "/etc/squid/extra/providers/extra-${id}.txt"`
    )
  }
  const rules = []
  for (const { id } of all) rules.push(`http_access allow from_app via_${id} dst_${id}`, `http_access allow from_app via_${id} extra_${id}`)
  for (const { id } of all) rules.push(`http_access allow from_app via_main dst_${id}`, `http_access allow from_app via_main extra_${id}`)
  return { ports: portLines, acls, rules }
}

/** squid.conf with its generated blocks (between "# BEGIN generated: <name>" and "# END generated: <name>" lines) refilled */
export function renderConf(conf, list) {
  const blocks = confBlocks(list)
  let out = conf
  for (const [name, lines] of Object.entries(blocks)) {
    const re = new RegExp(`(^# BEGIN generated: ${name}\\b[^\\n]*\\n)[\\s\\S]*?(^# END generated: ${name}\\b)`, 'm')
    if (!re.test(out)) throw new Error(`squid.conf has no "generated: ${name}" markers`)
    out = out.replace(re, (_m, begin, end) => `${begin}${lines.join('\n')}\n${end}`)
  }
  return out
}

/**
 * docker-compose.egress.yml carries COPIES of squid.conf and banks.txt (inline `configs:`), so one
 * extra file is all a user downloads. Between its "# BEGIN <name>" and "# END <name>" lines goes the
 * file's text, indented for YAML, with `$` doubled (compose would read `$x` as a variable).
 */
export function inlineInto(compose, name, text) {
  const begin = `      # BEGIN ${name}\n`
  const end = `\n      # END ${name}`
  const i = compose.indexOf(begin)
  const j = compose.indexOf(end, i)
  if (i < 0 || j < 0) throw new Error(`docker-compose.egress.yml has no BEGIN/END ${name} markers`)
  const body = text
    .replace(/\n$/, '')
    .split('\n')
    .map(l => (l ? `      ${l.replaceAll('$', '$$$$')}` : ''))
    .join('\n')
  return compose.slice(0, i + begin.length) + body + compose.slice(j)
}

/** The override file as it should be, given the current squid.conf, banks.txt and init.sh text */
export function renderCompose(compose, squidConf, banks, init = fs.readFileSync(INIT_SH, 'utf8')) {
  return inlineInto(inlineInto(inlineInto(compose, 'squid.conf', squidConf), 'banks.txt', banks), 'init.sh', init)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const list = loadAllowlist()
  const text = render(list)
  const conf = renderConf(fs.readFileSync(SQUID_CONF, 'utf8'), list)
  const compose = fs.readFileSync(EGRESS_COMPOSE, 'utf8')
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(BANKS_TXT) || fs.readFileSync(BANKS_TXT, 'utf8') !== text || fs.readFileSync(SQUID_CONF, 'utf8') !== conf || renderCompose(compose, conf, text) !== compose) {
      console.error('docker/squid/banks.txt, squid.conf or docker-compose.egress.yml is stale: run node scripts/egress-allowlist.mjs')
      process.exit(1)
    }
  } else {
    fs.writeFileSync(BANKS_TXT, text)
    fs.writeFileSync(SQUID_CONF, conf)
    fs.writeFileSync(EGRESS_COMPOSE, renderCompose(compose, conf, text))
    console.log('wrote docker/squid/banks.txt, the generated blocks of squid.conf and the copies in docker-compose.egress.yml')
  }
}
