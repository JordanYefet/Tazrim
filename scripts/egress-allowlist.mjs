/**
 * Renders docker/squid/banks.txt (the Squid allowlist, ENG-131) from docker/squid/allowlist.json,
 * the single source of truth.
 *
 *   node scripts/egress-allowlist.mjs          writes docker/squid/banks.txt, and refreshes the copies of it
 *                                              and of squid.conf inside docker-compose.egress.yml
 *   node scripts/egress-allowlist.mjs --check  exits 1 when either is stale
 *
 * Squid's dstdomain wants one entry per line, and warns about (and ignores) an entry that a
 * broader one already covers, so those are written as comments instead.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
export const ALLOWLIST_JSON = path.join(here, '../docker/squid/allowlist.json')
export const BANKS_TXT = path.join(here, '../docker/squid/banks.txt')
export const SQUID_CONF = path.join(here, '../docker/squid/squid.conf')
export const EGRESS_COMPOSE = path.join(here, '../docker-compose.egress.yml')

export function loadAllowlist(file = ALLOWLIST_JSON) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

/** ".a.com" covers "a.com" and every subdomain; "a.com" covers only itself */
export function covers(broad, narrow) {
  if (broad === narrow) return true
  return broad.startsWith('.') && (narrow === broad.slice(1) || narrow.endsWith(broad))
}

/** Every domain in the file (own and third-party), in file order, with its provider and why */
export function entries(list) {
  const out = []
  for (const [id, p] of Object.entries(list.providers)) {
    for (const d of p.domains) out.push({ id, domain: d, kind: 'own', why: '' })
    for (const t of p.thirdParty ?? []) out.push({ id, domain: t.domain, kind: 'third-party', why: t.why ?? '' })
  }
  return out
}

export function render(list) {
  const all = entries(list)
  const lines = [
    '# GENERATED by scripts/egress-allowlist.mjs from docker/squid/allowlist.json: do not edit here.',
    '# What the tazrim container may reach through Squid: one dstdomain per line.',
    '# A leading dot matches the domain and every subdomain; no dot = that exact host only.',
    '# "third-party" = a host the provider\'s pages load that login needs (found by scripts/egress-survey.mjs).',
    '',
  ]
  for (const [id, p] of Object.entries(list.providers)) {
    lines.push(`# --- ${id}: ${p.name}`)
    const mine = all.filter(e => e.id === id)
    for (const e of mine) {
      // Covered by a broader entry anywhere, or by the same domain listed earlier
      const at = all.indexOf(e)
      const by = all.find((o, i) => o !== e && covers(o.domain, e.domain) && (o.domain !== e.domain || i < at))
      const note = e.kind === 'third-party' ? ` # third-party${e.why ? `: ${e.why}` : ''}` : ''
      if (by) lines.push(`# ${e.domain}  (already covered by ${by.domain}, listed under ${by.id})`)
      else {
        lines.push(`${e.domain}${note}`)
      }
    }
    lines.push('')
  }
  return lines.join('\n')
}

/**
 * docker-compose.egress.yml carries COPIES of squid.conf and banks.txt (inline `configs:`), so one
 * extra file is all a user downloads. Between its "# BEGIN <name>" and "# END <name>" lines goes the
 * file's text, indented for YAML, with `$` doubled (compose would read `$x` as a variable).
 */
export function inlineInto(compose, name, text) {
  const begin = `      # BEGIN ${name}\n`
  const end = `\n      # END ${name}`
  const i = compose.indexOf(begin)
  const j = compose.indexOf(end, i)
  if (i < 0 || j < 0) throw new Error(`docker-compose.egress.yml has no BEGIN/END ${name} markers`)
  const body = text
    .replace(/\n$/, '')
    .split('\n')
    .map(l => (l ? `      ${l.replaceAll('$', '$$$$')}` : ''))
    .join('\n')
  return compose.slice(0, i + begin.length) + body + compose.slice(j)
}

/** The override file as it should be, given the current squid.conf and banks text */
export function renderCompose(compose, squidConf, banks) {
  return inlineInto(inlineInto(compose, 'squid.conf', squidConf), 'banks.txt', banks)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(loadAllowlist())
  if (process.argv.includes('--check')) {
    const compose = fs.readFileSync(EGRESS_COMPOSE, 'utf8')
    if (!fs.existsSync(BANKS_TXT) || fs.readFileSync(BANKS_TXT, 'utf8') !== text || renderCompose(compose, fs.readFileSync(SQUID_CONF, 'utf8'), text) !== compose) {
      console.error('docker/squid/banks.txt or docker-compose.egress.yml is stale: run node scripts/egress-allowlist.mjs')
      process.exit(1)
    }
  } else {
    fs.writeFileSync(BANKS_TXT, text)
    const compose = fs.readFileSync(EGRESS_COMPOSE, 'utf8')
    fs.writeFileSync(EGRESS_COMPOSE, renderCompose(compose, fs.readFileSync(SQUID_CONF, 'utf8'), text))
    console.log('wrote docker/squid/banks.txt and the copies in docker-compose.egress.yml')
  }
}
