#!/usr/bin/env node
/**
 * Writes lib/background/wallpapers.data.ts: the contour lines of the
 * "טופוגרפי" tile and the wave crests of "גלים", made by
 * lib/background/wallpaper-gen.ts.
 *
 *   node scripts/gen-wallpaper-data.mjs            -> rewrite the data file
 *   node scripts/gen-wallpaper-data.mjs out.svg    -> also write a 2x2 preview SVG of the contour tile
 *
 * Committed rather than generated at runtime so the server and every browser
 * draw exactly the same paths (see lines.ts).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { TOPO_TILE, generateTopoTile, generateWaveCrests } from '../lib/background/wallpaper-gen.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const topo = generateTopoTile()
const crests = generateWaveCrests()

const file = `// Generated by scripts/gen-wallpaper-data.mjs from lib/background/wallpaper-gen.ts. Do not edit.
import type { TopoPath } from './wallpaper-gen'

/** The contour lines of one ${TOPO_TILE.width} × ${TOPO_TILE.height} tile (they end on its edges and go on from the opposite edge) */
export const TOPO_PATHS: ReadonlyArray<TopoPath> = [
${topo.map(p => `  { d: '${p.d}', major: ${p.major} },`).join('\n')}
]

/** The crest of each wave band, back to front, in the 300 × 620 waves box */
export const WAVE_CRESTS: ReadonlyArray<string> = [
${crests.map(d => `  '${d}',`).join('\n')}
]
`
fs.writeFileSync(path.join(root, 'lib/background/wallpapers.data.ts'), file)
console.log(`${topo.length} contour lines, ${(file.length / 1024).toFixed(1)} KB`)

const preview = process.argv[2]
if (preview) {
  const { width: W, height: H } = TOPO_TILE
  const tile = topo.map(p => `<path d="${p.d}" stroke-width="${p.major ? 1.1 : 0.8}" stroke-opacity="${p.major ? 0.5 : 0.3}"/>`).join('')
  const uses = [0, 1].flatMap(i => [0, 1].map(j => `<use href="#t" x="${i * W}" y="${j * H}"/>`)).join('')
  fs.writeFileSync(
    preview,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W * 2}" height="${H * 2}" style="background:#fff">
<defs><clipPath id="c"><rect width="${W}" height="${H}"/></clipPath>
<g id="t" clip-path="url(#c)" fill="none" stroke="#1e293b" stroke-linecap="round" stroke-linejoin="round">${tile}</g></defs>
${uses}<path d="M${W} 0V${H * 2}M0 ${H}H${W * 2}" stroke="#f00" stroke-width="1" opacity="0.3"/></svg>`
  )
}
