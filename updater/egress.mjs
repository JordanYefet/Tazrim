/**
 * Network isolation, managed from the app (ENG-131/133/134). What may LOOSEN the Squid filter
 * (turn isolation off, add or remove a domain, remove an approver) needs a signature the app
 * cannot make: a passkey checked in here against public keys the app cannot write (the keys and
 * every file below live in the install folder, which only this helper mounts read-write), or the
 * approval password. Tightening (turn on) needs only the helper's token.
 *
 * Known limit: WebAuthn shows the person nothing about WHAT they approve, so an app that is
 * already compromised could show "add x" and ask for the approval of "turn off". The change log
 * (changes.jsonl), written here, records exactly what each approval was for.
 *
 * Files in <install>/egress/ (updater-owned; the app gets the folder read-only):
 *   extra-domains.json  [{ domain, note, addedAt, approver }]
 *   extra-domains.txt   generated from it: what Squid reads (acl extra)
 *   changes.jsonl       append-only { at, action, detail, approver }
 *   approvers.json      passkeys and at most one password
 * And <install>/tazrim-approval-code.txt (outside egress/: the app never sees it) holds the
 * one-time code that proves the person is at this computer when they register an approver.
 */
import crypto from 'node:crypto'
import nodeFs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { EGRESS_FILE } from './config.mjs'
import { checkDomain, covers } from './egress-rules.mjs'
import { copyNew, isRealDir, isRealFile, readPlain, realDir, writeText } from './files.mjs'
import { challengeOf, checkPassword, credentialIdOf, b64u, hashPassword, MIN_PASSWORD, verifyAssertion, verifyRegistration } from './passkey.mjs'

export const INSTALL_DIR = '/install'
export const CODE_FILE = 'tazrim-approval-code.txt'
export const CODE_TTL_MS = 10 * 60 * 1000
export const CODE_TRIES = 5
export const APPROVAL_TTL_MS = 2 * 60 * 1000
export const PASSWORD_TRIES = 5
export const PASSWORD_LOCK_MS = 15 * 60 * 1000
export const KEEP_CHANGES = 50

const ACTIONS = ['add-domain', 'remove-domain', 'turn-on', 'turn-off', 'add-approver', 'remove-approver']
const STATUS = { BAD_SIGNATURE: 403, BAD_PASSWORD: 403, LOCKED: 429, NOT_FOUND: 404, BUSY: 409, ALREADY_ALLOWED: 409, ALREADY_ON: 409, ALREADY_OFF: 409, NO_APPROVER: 409, NOT_AVAILABLE: 422, RECONFIGURE_FAILED: 500, INTERNAL: 500 }
const HOST_RE = /^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)*$/

const fail = (code, detail, extra) => ({ status: STATUS[code] ?? 400, body: { error: code, ...(detail ? { detail } : {}), ...extra } })
const ok = (body, status = 200) => ({ status, body })

const same = (a, b) => {
  const x = crypto.createHash('sha256').update(String(a)).digest()
  const y = crypto.createHash('sha256').update(String(b)).digest()
  return crypto.timingSafeEqual(x, y)
}
const publicApprover = a => ({ id: a.id, kind: a.kind ?? 'passkey', name: a.name, ...(a.kind === 'password' ? {} : { rpId: a.rpId }), createdAt: a.createdAt })
const isPasskey = a => (a.kind ?? 'passkey') === 'passkey'

/** squid dstdomain file for the extra domains: one per line, entries a broader one covers are comments */
export function renderExtraTxt(list) {
  const lines = [
    '# GENERATED by the Tazrim updater from extra-domains.json: do not edit (changes are overwritten).',
    '# Sites you added in the app (Settings -> network isolation); each needed an approval.',
    '',
  ]
  list.forEach((e, i) => {
    const by = list.find((o, j) => o !== e && covers(o.domain, e.domain) && (o.domain !== e.domain || j < i))
    lines.push(by ? `# ${e.domain}  (already covered by ${by.domain})` : e.domain)
  })
  return `${lines.join('\n')}\n`
}

function defaultBankDomains() {
  try {
    const file = fileURLToPath(new URL('../docker/squid/allowlist.json', import.meta.url))
    const list = JSON.parse(nodeFs.readFileSync(file, 'utf8'))
    return Object.values(list.providers).flatMap(p => [...p.domains, ...(p.thirdParty ?? []).map(t => t.domain)])
  } catch {
    return []
  }
}

export function createEgress({
  config,
  docker,
  lock,
  installDir = INSTALL_DIR,
  fs = nodeFs,
  now = () => new Date(),
  overrideSource = fileURLToPath(new URL('../docker/docker-compose.egress.yml', import.meta.url)),
  bankDomains = defaultBankDomains(),
  squidService = 'squid',
}) {
  const dir = path.join(installDir, 'egress')
  const files = {
    json: path.join(dir, 'extra-domains.json'),
    txt: path.join(dir, 'extra-domains.txt'),
    log: path.join(dir, 'changes.jsonl'),
    approvers: path.join(dir, 'approvers.json'),
    code: path.join(installDir, CODE_FILE),
    override: path.join(installDir, EGRESS_FILE),
  }

  const owner = () => {
    const st = fs.statSync(installDir)
    return { uid: st.uid, gid: st.gid }
  }

  function ensureDir() {
    const existed = isRealDir(dir, fs)
    realDir(dir, fs)
    if (!existed) {
      const o = owner()
      fs.chownSync(dir, o.uid, o.gid)
    }
  }

  function readJson(file, fallback) {
    try {
      const v = JSON.parse(readPlain(file, fs) ?? 'null')
      return Array.isArray(v) ? v : fallback
    } catch {
      return fallback
    }
  }

  /** Replaces `file` atomically (a fresh temp file renamed over it), owned like the install folder */
  function writeAtomic(file, text, mode = 0o644) {
    ensureDir()
    const tmp = `${file}.tmp-${crypto.randomBytes(4).toString('hex')}`
    writeText(tmp, text, { mode, owner: owner(), fs })
    try {
      fs.renameSync(tmp, file)
    } catch (e) {
      fs.rmSync(tmp, { force: true })
      throw e
    }
  }

  const extras = () => readJson(files.json, [])
  const approvers = () => readJson(files.approvers, [])
  const saveApprovers = list => writeAtomic(files.approvers, `${JSON.stringify(list, null, 2)}\n`)

  function log(action, detail, approver) {
    ensureDir()
    const line = `${JSON.stringify({ at: now().toISOString(), action, detail, approver: approver ?? null })}\n`
    const { O_WRONLY, O_APPEND, O_CREAT, O_NOFOLLOW } = nodeFs.constants
    const fd = fs.openSync(files.log, O_WRONLY | O_APPEND | O_CREAT | O_NOFOLLOW, 0o644)
    try {
      const o = owner()
      fs.fchownSync(fd, o.uid, o.gid)
      fs.writeSync(fd, line)
    } finally {
      fs.closeSync(fd)
    }
  }

  function changes() {
    const text = readPlain(files.log, fs) ?? ''
    const out = []
    for (const l of text.split('\n').slice(-(KEEP_CHANGES + 5)).reverse()) {
      try {
        const e = JSON.parse(l)
        if (ACTIONS.includes(e?.action)) out.push(e)
      } catch {
        // a half-written line
      }
    }
    return out.slice(0, KEEP_CHANGES)
  }

  // ---- squid ---------------------------------------------------------------------------------

  /** Squid reads the new file; resolves { ran: false } when it isn't running (isolation off) */
  async function reload() {
    const id = await docker.findService(squidService)
    if (!id) return { ran: false }
    const r = await docker.exec(id, ['squid', '-k', 'reconfigure'])
    if (r.exitCode !== 0) throw new Error(`squid -k reconfigure exited with ${r.exitCode}`)
    return { ran: true }
  }

  function putFiles(list) {
    writeAtomic(files.json, `${JSON.stringify(list, null, 2)}\n`)
    writeAtomic(files.txt, renderExtraTxt(list))
  }

  /** Writes the new list, tells Squid; on a failure the old files come back (and Squid is told again) */
  async function applyDomains(list) {
    const before = { json: readPlain(files.json, fs), txt: readPlain(files.txt, fs) }
    putFiles(list)
    try {
      await reload()
    } catch (e) {
      for (const k of ['json', 'txt']) {
        if (before[k] === null) fs.rmSync(files[k], { force: true })
        else writeAtomic(files[k], before[k])
      }
      await reload().catch(() => {})
      throw Object.assign(new Error(String(e?.message ?? e)), { code: 'RECONFIGURE_FAILED' })
    }
  }

  // ---- isolation on / off ----------------------------------------------------------------------

  /** Files isolation needs: the override file (never overwriting one that exists) and an empty egress/ */
  function prepareOn() {
    ensureDir()
    if (!isRealFile(files.json, fs)) writeAtomic(files.json, '[]\n')
    if (!isRealFile(files.txt, fs)) writeAtomic(files.txt, renderExtraTxt([]))
    let exists = true
    try {
      fs.lstatSync(files.override)
    } catch {
      exists = false
    }
    if (!exists) copyNew(overrideSource, files.override, { mode: 0o644, owner: owner(), fs })
  }

  function overrideState() {
    const mine = readPlain(files.override, fs)
    const image = readPlain(overrideSource, fs)
    return { overridePresent: mine !== null, overrideDiffers: mine !== null && image !== null && mine !== image }
  }

  const turnOn = () => config.startEgress(true, { prepare: prepareOn })

  // ---- registration of approvers -----------------------------------------------------------------

  let pending = null // { challenge, rpId, code, expires, tries }
  let timer = null

  function cancelRegistration() {
    pending = null
    clearTimeout(timer)
    fs.rmSync(files.code, { force: true })
  }

  function sweep() {
    if (pending && now().getTime() >= pending.expires) cancelRegistration()
  }

  const validRpId = v => typeof v === 'string' && HOST_RE.test(v)

  function registerBegin(body) {
    if (!validRpId(body?.rpId)) return fail('BAD_RPID')
    const userName = typeof body?.userName === 'string' && body.userName.trim() ? body.userName.trim().slice(0, 64) : 'Tazrim'
    const rpName = typeof body?.rpName === 'string' && body.rpName.trim() ? body.rpName.trim().slice(0, 64) : 'Tazrim'
    sweep()
    const code = String(crypto.randomInt(0, 1_000_000)).padStart(6, '0')
    const expires = now().getTime() + CODE_TTL_MS
    // The code file goes in the install folder itself, not in egress/: the app never mounts that
    writeText(files.code, `${code}\n`, { mode: 0o600, owner: owner(), fs })
    clearTimeout(timer)
    timer = setTimeout(sweep, CODE_TTL_MS + 1000)
    timer.unref?.()
    const challenge = b64u(crypto.randomBytes(32))
    pending = { challenge, rpId: body.rpId, code, expires, tries: 0 }
    const options = {
      challenge,
      rp: { id: body.rpId, name: rpName },
      user: { id: b64u(crypto.randomBytes(16)), name: userName, displayName: userName },
      pubKeyCredParams: [
        { type: 'public-key', alg: -7 },
        { type: 'public-key', alg: -8 },
        { type: 'public-key', alg: -257 },
      ],
      authenticatorSelection: { residentKey: 'preferred', userVerification: 'required' },
      attestation: 'none',
      timeout: 120000,
      excludeCredentials: approvers()
        .filter(a => isPasskey(a) && a.rpId === body.rpId)
        .map(a => ({ type: 'public-key', id: a.id })),
    }
    return ok({ options, codeFile: CODE_FILE, expiresAt: new Date(expires).toISOString() })
  }

  async function registerFinish(body) {
    sweep()
    if (!pending) return fail('NO_REGISTRATION')
    const name = typeof body?.name === 'string' ? body.name.trim() : ''
    if (!name || name.length > 60) return fail('BAD_NAME')
    if (typeof body?.code !== 'string' || !same(body.code.trim(), pending.code)) {
      pending.tries++
      if (pending.tries >= CODE_TRIES) {
        cancelRegistration()
        return fail('TOO_MANY_TRIES')
      }
      return fail('BAD_CODE')
    }
    const at = now().toISOString()
    const list = approvers()
    let entry
    let detail = name
    if ('password' in (body ?? {}) && !body.response) {
      const pw = body.password
      if (typeof pw !== 'string' || [...pw].length < MIN_PASSWORD || pw.length > 256) return fail('WEAK_PASSWORD')
      const h = await hashPassword(pw)
      entry = { id: b64u(crypto.randomBytes(12)), kind: 'password', name, ...h, createdAt: at }
      const old = list.findIndex(a => a.kind === 'password')
      if (old >= 0) {
        list.splice(old, 1)
        detail = `${name} (password replaced)`
      }
    } else {
      const v = verifyRegistration(body?.response, { challenge: pending.challenge, rpId: pending.rpId })
      if (!v.ok) return fail(v.code)
      entry = { id: v.id, kind: 'passkey', name, publicKey: v.publicKey, alg: v.alg, rpId: pending.rpId, origin: v.origin, createdAt: at }
      const dup = list.findIndex(a => a.id === entry.id)
      if (dup >= 0) list.splice(dup, 1)
    }
    list.push(entry)
    saveApprovers(list)
    cancelRegistration()
    log('add-approver', detail, name)
    return ok({ ok: true, approver: publicApprover(entry) })
  }

  // ---- approvals ---------------------------------------------------------------------------------

  const flows = new Map() // flowId -> { challenge, change, rpId, expires }
  const lockState = { fails: [], until: 0 }

  function sweepFlows() {
    const t = now().getTime()
    for (const [id, f] of flows) if (t >= f.expires + APPROVAL_TTL_MS) flows.delete(id)
  }

  /** Checks a requested change against what is true now; { change } (normalised) or a refusal */
  async function validateChange(c) {
    switch (c?.action) {
      case 'add-domain': {
        const d = checkDomain(c.domain)
        if (!d.ok) return fail(d.code)
        const note = typeof c.note === 'string' ? c.note.trim().slice(0, 200) : ''
        if (bankDomains.some(b => covers(b, d.domain)) || extras().some(e => covers(e.domain, d.domain))) return fail('ALREADY_ALLOWED')
        return { change: { action: 'add-domain', domain: d.domain, note } }
      }
      case 'remove-domain': {
        const d = checkDomain(c.domain)
        if (!d.ok) return fail(d.code)
        if (!extras().some(e => e.domain === d.domain)) return fail('NOT_FOUND')
        return { change: { action: 'remove-domain', domain: d.domain } }
      }
      case 'remove-approver':
        if (typeof c.id !== 'string' || !approvers().some(a => a.id === c.id)) return fail('NOT_FOUND')
        return { change: { action: 'remove-approver', id: c.id } }
      case 'turn-off': {
        const { ctx, reason } = await config.context()
        if (!ctx) return fail('NOT_AVAILABLE', reason)
        if (!ctx.configFiles.some(f => f.endsWith(`/${EGRESS_FILE}`))) return fail('ALREADY_OFF')
        return { change: { action: 'turn-off' } }
      }
      default:
        return fail('BAD_CHANGE')
    }
  }

  async function approveBegin(body) {
    if (!validRpId(body?.rpId)) return fail('BAD_RPID')
    if (lock.busy) return fail('BUSY')
    const v = await validateChange(body?.change)
    if (v.status) return v
    const all = approvers()
    const passkeys = all.filter(a => isPasskey(a) && a.rpId === body.rpId)
    const passwordAllowed = all.some(a => a.kind === 'password')
    if (!passkeys.length && !passwordAllowed) return fail('NO_APPROVER')
    sweepFlows()
    const flowId = b64u(crypto.randomBytes(16))
    const challenge = b64u(crypto.randomBytes(32))
    flows.set(flowId, { challenge, change: v.change, rpId: body.rpId, expires: now().getTime() + APPROVAL_TTL_MS })
    const options = passkeys.length
      ? {
          challenge,
          rpId: body.rpId,
          allowCredentials: passkeys.map(a => ({ type: 'public-key', id: a.id })),
          userVerification: 'required',
          timeout: 120000,
        }
      : null
    return ok({ flowId, options, passwordAllowed, change: v.change })
  }

  /** Takes the pending approval out (single use); { flow } or a refusal */
  function takeFlow({ flowId, challenge }) {
    let id = flowId
    if (!id && challenge) id = [...flows].find(([, f]) => f.challenge === challenge)?.[0]
    const flow = typeof id === 'string' ? flows.get(id) : undefined
    if (!flow || (challenge && flow.challenge !== challenge)) return fail('CHALLENGE_UNKNOWN')
    flows.delete(id)
    if (now().getTime() >= flow.expires) return fail('CHALLENGE_EXPIRED')
    return { flow }
  }

  async function approveFinish(body) {
    sweepFlows()
    const usingPassword = typeof body?.password === 'string' && !body?.response
    let approverName
    let flow
    if (usingPassword) {
      if (typeof body.flowId !== 'string') return fail('CHALLENGE_UNKNOWN')
      const t = now().getTime()
      lockState.fails = lockState.fails.filter(x => t - x < PASSWORD_LOCK_MS)
      if (lockState.until > t) return fail('LOCKED', undefined, { until: new Date(lockState.until).toISOString() })
      const taken = takeFlow({ flowId: body.flowId })
      if (!taken.flow) return taken
      flow = taken.flow
      const pw = approvers().find(a => a.kind === 'password')
      if (!pw) return fail('NO_APPROVER')
      if (!(await checkPassword(body.password, pw))) {
        lockState.fails.push(t)
        if (lockState.fails.length >= PASSWORD_TRIES) {
          lockState.until = t + PASSWORD_LOCK_MS
          lockState.fails = []
        }
        return fail('BAD_PASSWORD')
      }
      lockState.fails = []
      approverName = `${pw.name} (סיסמה)`
    } else {
      const response = body?.response
      const challenge = challengeOf(response)
      if (!challenge) return fail('BAD_CLIENT_DATA')
      const taken = takeFlow({ challenge })
      if (!taken.flow) return taken
      flow = taken.flow
      const credId = credentialIdOf(response)
      const approver = approvers().find(a => isPasskey(a) && a.id === credId && a.rpId === flow.rpId)
      if (!approver) return fail('UNKNOWN_CREDENTIAL')
      const v = verifyAssertion(response, approver, flow.challenge)
      if (!v.ok) return fail(v.code)
      approverName = approver.name
    }

    // Things may have changed during the minutes the person took
    const again = await validateChange(flow.change)
    if (again.status) return again
    return applyChange(again.change, approverName)
  }

  async function applyChange(c, approverName) {
    switch (c.action) {
      case 'add-domain': {
        if (lock.busy) return fail('BUSY')
        const list = [...extras(), { domain: c.domain, note: c.note, addedAt: now().toISOString(), approver: approverName }]
        try {
          await applyDomains(list)
        } catch (e) {
          return fail(e?.code ?? 'INTERNAL', e?.message)
        }
        log('add-domain', c.domain, approverName)
        return ok({ ok: true, change: c })
      }
      case 'remove-domain': {
        if (lock.busy) return fail('BUSY')
        try {
          await applyDomains(extras().filter(e => e.domain !== c.domain))
        } catch (e) {
          return fail(e?.code ?? 'INTERNAL', e?.message)
        }
        log('remove-domain', c.domain, approverName)
        return ok({ ok: true, change: c })
      }
      case 'remove-approver': {
        const list = approvers()
        const gone = list.find(a => a.id === c.id)
        saveApprovers(list.filter(a => a.id !== c.id))
        log('remove-approver', gone?.name ?? c.id, approverName)
        return ok({ ok: true, change: c })
      }
      case 'turn-off': {
        const r = await config.startEgress(false)
        if (r.status !== 202) return fail(r.code ?? 'INTERNAL', r.error)
        log('turn-off', '', approverName)
        return ok({ ok: true, change: c, job: r.job }, 200)
      }
    }
    return fail('BAD_CHANGE')
  }

  return {
    files,

    /** GET /v1/egress */
    async info() {
      sweep()
      const { ctx, reason } = await config.context()
      const job = config.current()
      return ok({
        available: Boolean(ctx),
        ...(ctx ? {} : { reason }),
        on: Boolean(ctx?.configFiles.some(f => f.endsWith(`/${EGRESS_FILE}`))),
        ...overrideState(),
        extraDomains: extras(),
        approvers: approvers().map(publicApprover),
        changes: changes(),
        registration: pending ? { pending: true, expiresAt: new Date(pending.expires).toISOString() } : null,
        ...(job?.egress ? { job } : {}),
      })
    },

    /** POST /v1/egress/on: only the token (tightening needs no approval) */
    async turnOn() {
      const r = await turnOn()
      if (r.status !== 202) return fail(r.code ?? 'INTERNAL', r.error, r.reason ? { reason: r.reason } : undefined)
      try {
        log('turn-on', '', null)
      } catch (e) {
        console.error('updater: could not log turn-on', e)
      }
      return ok({ job: r.job }, 202)
    },

    registerBegin,
    registerFinish,
    approveBegin,
    approveFinish,
  }
}
